// Generates src/lib/master-data.ts from the KYN master CSVs in data/master/.
// Run: node scripts/gen-master-data.mjs
import { readFileSync, writeFileSync } from "fs";
import path from "path";

const dir = path.join(process.cwd(), "data", "master");
const rows = (file) => {
  const txt = readFileSync(path.join(dir, file), "utf8").replace(/^﻿/, "").trim();
  const [head, ...body] = txt.split(/\r?\n/);
  const cols = head.split(",");
  return body.filter(Boolean).map((line) => {
    const cells = line.split(",");
    return Object.fromEntries(cols.map((c, i) => [c, (cells[i] ?? "").trim()]));
  });
};
const q = (s) => JSON.stringify(s ?? "");

const flowers = rows("thailand_cut_flowers_list.csv");
const packaging = rows("flower_shipping_packaging_ef_list.csv");
const vehicles = rows("vehicle_and_fuel_mapping_list.csv");

const out = `// AUTO-GENERATED by scripts/gen-master-data.mjs — do not edit by hand.
// Source: data/master/*.csv (master reference data supplied by KYN, 24 Aug 2026).

export interface FlowerEntry {
  category: string; categoryEn: string;
  type: string; typeEn: string;
  variant: string; variantEn: string;
}

/** ${flowers.length} varieties across ${new Set(flowers.map((f) => f.Type_TH)).size} types — thailand_cut_flowers_list */
export const FLOWERS: FlowerEntry[] = [
${flowers
  .map(
    (f) =>
      `  { category: ${q(f.Category_TH)}, categoryEn: ${q(f.Category_EN)}, type: ${q(f.Type_TH)}, typeEn: ${q(
        f.Type_EN,
      )}, variant: ${q(f.Variant_TH)}, variantEn: ${q(f.Variant_EN)} },`,
  )
  .join("\n")}
];

/** Distinct flower types (Type_TH), in master-list order. */
export const FLOWER_TYPES: string[] = Array.from(new Set(FLOWERS.map((f) => f.type)));

/** Varieties belonging to one type — powers the cascading Type → Variety suggestion. */
export function variantsForType(type: string): string[] {
  const t = (type ?? "").trim();
  if (!t) return Array.from(new Set(FLOWERS.map((f) => f.variant)));
  return FLOWERS.filter((f) => f.type === t).map((f) => f.variant);
}

/** All variety names (used when no type is chosen yet). */
export const FLOWER_VARIANTS: string[] = Array.from(new Set(FLOWERS.map((f) => f.variant)));

export interface PackagingMaterial {
  category: string; material: string; materialEn: string;
  unit: string; efRange: string; efDefault: number;
  lifespan: string; standardWeight: string; note: string;
}

/** ${packaging.length} materials — flower_shipping_packaging_ef_list */
export const PACKAGING_MATERIALS: PackagingMaterial[] = [
${packaging
  .map(
    (m) =>
      `  { category: ${q(m.Category_TH)}, material: ${q(m.Material_TH)}, materialEn: ${q(m.Material_EN)}, unit: ${q(
        m.Unit,
      )}, efRange: ${q(m.EF_Range)}, efDefault: ${Number(m.EF_Default)}, lifespan: ${q(
        m.Lifespan_Cycles,
      )}, standardWeight: ${q(m.Standard_Weight_kg)}, note: ${q(m.Note_TH)} },`,
  )
  .join("\n")}
];

export interface VehicleFuel {
  category: string; vehicle: string; vehicleEn: string;
  fuel: string; fuelEn: string;
  vehicleKey: string; fuelKey: string;
}

/** ${vehicles.length} vehicle x fuel pairs — vehicle_and_fuel_mapping_list.
 *  NOTE: KYN supplied the mapping/enum only — EF_tkm / EF_vkm values are NOT in the file
 *  and must be obtained from KYN or TGO before the transport formula can use them. */
export const VEHICLE_FUELS: VehicleFuel[] = [
${vehicles
  .map(
    (v) =>
      `  { category: ${q(v.Category_TH)}, vehicle: ${q(v.Vehicle_Type_TH)}, vehicleEn: ${q(
        v.Vehicle_Type_EN,
      )}, fuel: ${q(v.Fuel_System_TH)}, fuelEn: ${q(v.Fuel_System_EN)}, vehicleKey: ${q(
        v.Database_Value_Vehicle,
      )}, fuelKey: ${q(v.Database_Value_Fuel)} },`,
  )
  .join("\n")}
];
`;

writeFileSync(path.join(process.cwd(), "src", "lib", "master-data.ts"), out, "utf8");
console.log(
  `generated src/lib/master-data.ts — flowers ${flowers.length}, packaging ${packaging.length}, vehicles ${vehicles.length}`,
);
